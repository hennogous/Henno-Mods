def xml_bytes(root):
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


def node(parent, name, value):
    return ET.SubElement(parent, name, {"text": str(value)})


def field(parent, kind, name, **values):
    row = ET.SubElement(parent, "Element", {"class": "AssetObjects.." + kind})
    for key, value in values.items():
        child = ET.SubElement(row, key)
        if isinstance(value, str):
            child.set("text", value)
        else:
            child.text = str(value)
    node(row, "m_ParamName", name)
    return row


def with_drop_shadow(image, offset, blur, opacity=.28):
    """Composite a soft black silhouette beneath the unchanged foreground art."""
    mask = image.getchannel("A").filter(ImageFilter.GaussianBlur(blur))
    shifted = Image.new("L", image.size, 0)
    shifted.paste(mask, offset)
    shadow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    shadow.putalpha(shifted.point(lambda alpha: round(alpha * opacity)))
    return Image.alpha_composite(shadow, image)


