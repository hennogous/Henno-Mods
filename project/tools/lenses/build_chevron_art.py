    # rather than returning to the old origin-half footprint. The native quad's
    # V=0 edge is forward (position.y=+0.5); this is verified from LinearWaveVB.
    # Stroke length5.36 / stride8 = 67%. The native 32-unit fade band remains
    # fixed: texture opacity follows the glyph, not a stationary end crop.
