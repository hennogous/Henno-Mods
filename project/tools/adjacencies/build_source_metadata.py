"""Generate human-readable metadata/localization for CSC adjacency sources."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DIRECTORY = ROOT / 'Civ Supply Chains/Lua_UI/Adjacencies'
LABELS = {
    'ROUTE': 'road level', 'WORKER': 'working citizen', 'UNIT': 'unit',
    'DISTRICT_AND_WONDER': 'district or Wonder', 'DISTRICT': 'district',
    'LAKE': 'lake', 'WATER_LEVEL': 'water access level', 'RESOURCE': 'visible resource',
    'WONDERS': 'completed Wonder', 'NATIONALPARK': 'National Park tile',
    'CAO_ROUTE': 'matching road', 'CAO_UNIT': 'matching unit',
    'CAO_RESOURCE_CLASS': 'matching resource', 'TYPETAG_RESOURCE': 'matching resource',
    'CAO_RESOURCE': 'matching resource', 'CAO_IMPROVEMENT': 'matching improvement',
    'CAO_DISTRICT': 'matching district', 'TYPETAG_DISTRICT': 'matching district',
    'CAO_FEATURE': 'matching feature', 'CAO_TERRAIN_SETS': 'matching terrain',
    'CAO_TERRAIN': 'matching terrain', 'SPECIFIC_WONDER': 'matching completed Wonder',
    'PLOT_PROPERTY': 'plot property point', 'PLOT_PROPERTY_HASHED': 'plot property point',
    'DISTRICT_PROPERTY': 'district property point', 'DISTRICT_PROPERTY_HASHED': 'district property point',
    'DISTRICT_MAX_HP': 'district maximum hit point', 'DISTRICT_DAMAGE': 'district damage point',
    'DISTRICT_REMAIN_HP': 'district remaining hit point', 'WALL_MAX_HP': 'wall maximum hit point',
    'WALL_DAMAGE': 'wall damage point', 'WALL_REMAIN_HP': 'wall remaining hit point',
    'DEFENSE_STRENGTH': 'defense strength point', 'DISTRICTS_CAO_YIELD': 'district yield point',
}
OVERLAYS = {'RESOURCE':'Terrain_Generic_Resource','LAKE':'Terrain_Coast',
            'WONDERS':'Generic_Wonder','SPECIFIC_WONDER':'Generic_Wonder',
            'DISTRICT':'Districts_Generic_District','DISTRICT_AND_WONDER':'Districts_Generic_District'}


def main():
    entries = {'FROM_RINGS_'+key:(label,OVERLAYS.get(key)) for key,label in LABELS.items()}
    for key in ['ROUTE','WORKER','UNIT','DISTRICT_AND_WONDER','DISTRICT','LAKE','WATER_LEVEL','RESOURCE','WONDERS']:
        entries['FROM_ADJACENT_'+key]=(LABELS[key],OVERLAYS.get(key))
    for key in ['PLOT_PROPERTY','PLOT_PROPERTY_HASHED','DISTRICT_PROPERTY','DISTRICT_PROPERTY_HASHED']:
        entries['FROM_'+key]=(LABELS[key],None)
    for key,label in {'UNIT_LEVELS':'unit level','APPEAL':'Appeal point','CAO_YIELD':'tile yield point',
                      'AIR_SLOTS':'air slot','AIR_UNITS':'air unit','SURPLUS_AIR_SLOTS':'unused air slot'}.items():
        entries['FROM_UI_RINGS_'+key]=(label,None)
    entries['FROM_RIVER_CROSSING']=('river edge','Terrain_River')
    entries['FROM_UNCONDITIONAL_BONUS']=('fixed bonus',None)
    sql=['-- Generated by project/tools/adjacencies/build_source_metadata.py.',
         'INSERT OR IGNORE INTO CSC_AdjacencySources (AdjacencyType,Name,ArtdefOverlayEntry) VALUES']
    # Only river edges need a source label today. Material/district names come
    # from Quarter objects or native definitions; hills use the object below.
    used_labels = {'FROM_RIVER_CROSSING': 'River edge'}
    for key,(_,overlay) in sorted(entries.items()):
        icon="'"+overlay+"'" if overlay else 'NULL'
        name='LOC_CSC_ADJ_SOURCE_'+key if key in used_labels else 'LOC_CSC_ADJ_SOURCE_GENERIC'
        sql.append(f"    ('{key}','{name}',{icon}),")
    sql[-1]=sql[-1][:-1]+';'
    sql.extend(["INSERT OR IGNORE INTO CSC_AdjacencyObjects (CustomAdjacentObject,Name) VALUES"])
    terrain={'IsHills':'Hills'}
    for key in terrain: sql.append(f"    ('{key}','LOC_CSC_ADJ_TERRAIN_{key}'),")
    sql[-1]=sql[-1][:-1]+';'
    (DIRECTORY/'CSC_AdjacencySources.sql').write_text('\n'.join(sql)+'\n',encoding='utf-8')
    markdown=['# CSC_ADJACENCY_SOURCES_TEXT','output: Civ Supply Chains/Text/CSC_ADJACENCY_SOURCES_TEXT.sql','language: en_US','']
    for key,label in sorted(used_labels.items()):
        plural=label+'s'
        text='{1_Count : plural 1?'+label+'; other?'+plural+';}'
        markdown.extend([f'## LOC_CSC_ADJ_SOURCE_{key}',text,''])
    for key,label in terrain.items(): markdown.extend([f'## LOC_CSC_ADJ_TERRAIN_{key}',label,''])
    (ROOT/'project/localization/CSC_ADJACENCY_SOURCES_TEXT.md').write_text('\n'.join(markdown),encoding='utf-8')
    print(f'Generated metadata for {len(entries)} sources')


if __name__ == '__main__': main()
